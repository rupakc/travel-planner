// Generates src/theme/tokens.css from design/tokens.json.
//   npm run tokens
// Each colour becomes a CSS variable holding space-separated RGB channels
// (`--c-gray-50: 249 250 251;`) so Tailwind's alpha modifiers keep working:
// tailwind.config.js maps `gray-50` to `rgb(var(--c-gray-50) / <alpha-value>)`.
// `:root` holds the light values, `html.dark` the dark ones.
import { readFileSync, writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'

export const STOPS = ['50', '100', '200', '300', '400', '500', '600', '700', '800', '900', '950']
export const FAMILIES = [
  'gray', 'slate', 'stone', 'teal', 'amber', 'sky', 'red', 'emerald', 'green', 'violet', 'rose', 'cyan',
  'blue', 'purple', 'yellow', 'indigo', 'pink', 'orange', 'lime', 'fuchsia', 'primary', 'accent',
]
export const SEMANTIC = ['surface', 'surface-raised', 'text', 'text-muted', 'border', 'accent']

export function channels(hex) {
  const m = /^#([0-9a-f]{6})$/i.exec(hex)
  if (!m) throw new Error(`Not a #rrggbb colour: ${hex}`)
  const n = parseInt(m[1], 16)
  return `${(n >> 16) & 255} ${(n >> 8) & 255} ${n & 255}`
}

// 'gray-50' -> mode.gray['50'], 'white' -> mode.white
function resolveRef(mode, ref) {
  if (ref === 'white') return mode.white
  const i = ref.lastIndexOf('-')
  const hex = mode[ref.slice(0, i)]?.[ref.slice(i + 1)]
  if (!hex) throw new Error(`Unknown semantic reference: ${ref}`)
  return hex
}

function block(selector, mode, semantic) {
  const lines = []
  for (const fam of FAMILIES) {
    for (const stop of STOPS) {
      const hex = mode[fam]?.[stop]
      if (!hex) throw new Error(`Missing ${fam}-${stop} in ${selector}`)
      lines.push(`  --c-${fam}-${stop}: ${channels(hex)};`)
    }
  }
  lines.push(`  --c-white: ${channels(mode.white)};`)
  for (const name of SEMANTIC) {
    lines.push(`  --c-${name}: ${channels(resolveRef(mode, semantic[name]))};`)
  }
  return `${selector} {\n${lines.join('\n')}\n}\n`
}

export function buildCss(tokens) {
  return [
    '/* Generated by scripts/build-tokens.mjs from design/tokens.json. Do not edit; run `npm run tokens`. */\n',
    block(':root', tokens.palette, tokens.semantic),
    block('html.dark', tokens.dark, tokens.semantic),
  ].join('\n')
}

const isMain = process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]
if (isMain) {
  const root = new URL('..', import.meta.url)
  const tokens = JSON.parse(readFileSync(new URL('design/tokens.json', root), 'utf8'))
  writeFileSync(new URL('src/theme/tokens.css', root), buildCss(tokens))
  console.log('wrote src/theme/tokens.css')
}
