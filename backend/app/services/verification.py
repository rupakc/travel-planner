def _flights(data: dict) -> dict:
    # `live_fare` is set only by the SerpAPI mapper (and stripped from LLM
    # output); `source` alone is not evidence — the model copies it from its
    # prompt example and URL enrichment rewrites it from the booking link.
    items = _items(data)
    live = sum(1 for f in items if f.get("live_fare") is True)
    total = len(items)
    counts = {"items_verified": live, "items_total": total}
    if total and live == total:
        return _result(
            "verified",
            "Live fares from Google Flights",
            [
                _check(
                    "Live fares", "pass", f"{live} of {total} fares from Google Flights"
                )
            ],
            **counts,
        )
    if live:
        return _result(
            "partial",
            "Some fares are live from Google Flights; the rest are AI estimates — check the airline.",
            [
                _check(
                    "Live fares", "pass", f"{live} of {total} fares from Google Flights"
                ),
                _check(
                    "Estimated fares",
                    "info",
                    f"{total - live} of {total} fares are AI estimates",
                ),
            ],
            **counts,
        )
    return _result(
        "unverified",
        "Estimated fares — prices change; check the airline",
        [_check("Estimated fares", "info", "Fares are AI estimates, not live prices")],
        **counts,
    )


def _hotels(data: dict, pending: bool) -> dict:
    # Only items enrichment actually searched carry a bool; absent = not searched
    searched = [h for h in _items(data) if isinstance(h.get("link_verified"), bool)]
    found = sum(1 for h in searched if h["link_verified"] is True)
    total = len(searched)
    checks = (
        [
            _check(
                "Hotel listings",
                "pass" if found else "info",
                f"Found online by name: {found} of {total}",
            )
        ]
        if total
        else []
    )
    counts = {"items_verified": found, "items_total": total, "pending": pending}
    if pending:
        return _result("unverified", _PENDING_SUMMARY, [], **counts)
    if total and found == total:
        return _result(
            "verified",
            "Every checked hotel was found online by name.",
            checks,
            **counts,
        )
    if found:
        return _result(
            "partial",
            "Some hotels were found online by name; verify the rest before booking.",
            checks,
            **counts,
        )
    if not total:
        return _result(
            "unverified",
            "No hotels were checked online — verify before booking.",
            checks,
            **counts,
        )
    return _result("unverified", _DEFAULT_SUMMARY, checks, **counts)


def _listings(data: dict, pending: bool, *, with_prices: bool) -> dict:
    # Only the resolver's top-N searched items carry `link_checked`; the rest
    # were never looked up, so they are not part of the totals.
    searched = [a for a in _items(data) if a.get("link_checked") is True]
    found = sum(1 for a in searched if a.get("link_verified") is True)
    total = len(searched)
    counts = {"items_verified": found, "items_total": total, "pending": pending}
    if pending:
        return _result("unverified", _PENDING_SUMMARY, [], **counts)
    if found:
        checks = [
            _check(
                "Specific listings",
                "pass",
                f"{found} of the {total} checked were found online by name",
            )
        ]
        summary = (
            "Some links point to listings found online by name; the rest are searches."
        )
        level = "partial"
    elif total:
        checks = [
            _check(
                "Specific listings",
                "info",
                f"None of the {total} checked were found online by name",
            )
        ]
        summary = _DEFAULT_SUMMARY
        level = "unverified"
    else:
        checks = [
            _check(
                "Specific listings", "info", "Links are searches, not specific listings"
            )
        ]
        summary = _DEFAULT_SUMMARY
        level = "unverified"
    if with_prices:
        checks.append(
            _check("Prices and ratings", "info", "Prices and ratings are AI estimates")
        )
    return _result(level, summary, checks, **counts)


def _walking_tours(data: dict) -> dict:
    checks = []
    ok = 0
    for s in data.get("sources") or []:
        if not isinstance(s, dict):
            continue
        provider = s.get("provider") or s.get("provider_key") or "Provider"
        city = f" ({s['city']})" if s.get("city") else ""
        if s.get("status") == "ok":
            ok += 1
            checks.append(
                _check(
                    f"{provider}{city}",
                    "pass",
                    f"{s.get('count', 0)} tours crawled from the provider's page",
                    _str_url(s.get("url")),
                )
            )
        else:
            checks.append(
                _check(
                    f"{provider}{city}",
                    "info",
                    "Provider page could not be read this time",
                    _str_url(s.get("url")),
                )
            )
    if ok and _items(data):
        return _result(
            "verified", "Listings crawled from the providers' own pages", checks
        )
    return _result(
        "unverified", "No provider listings could be confirmed this time.", checks
    )


def _weather(data: dict) -> dict:
    source = data.get("source") if isinstance(data.get("source"), str) else ""
    if source == "open-meteo":
        return _result(
            "verified",
            "Open-Meteo forecast/climate data",
            [
                _check(
                    "Open-Meteo",
                    "pass",
                    "Forecast/climate data from Open-Meteo",
                    "https://open-meteo.com",
                )
            ],
        )
    if "open-meteo" in source and "llm-estimate" in source:
        return _result(
            "partial",
            "Partly Open-Meteo data; some cities are AI climate estimates.",
            [
                _check(
                    "Open-Meteo",
                    "pass",
                    "Some cities from Open-Meteo",
                    "https://open-meteo.com",
                ),
                _check("AI estimate", "info", "Some cities are AI climate estimates"),
            ],
        )
    return _result(
        "unverified",
        "AI climate estimate — check a forecast closer to your trip.",
        [_check("AI estimate", "info", "No live forecast data was available")],
    )


def _events(data: dict) -> dict:
    items = _items(data)
    checks = []
    if items:
        confirmed = sum(
            1 for e in items if e.get("date_certainty") == "confirmed_annual"
        )
        checks.append(
            _check(
                "Event dates",
                "info",
                f"{confirmed} of {len(items)} dates confirmed annual",
            )
        )
    return _result("unverified", _DEFAULT_SUMMARY, checks)


def _facts(data: dict) -> dict:
    """Place facts: sourced crawler facts vs AI-suggested ones."""
    facts = [
        f
        for p in data.get("places") or []
        if isinstance(p, dict)
        for group in (p.get("groups") or {}).values()
        if isinstance(group, list)
        for f in group
        if isinstance(f, dict)
    ]
    # Sourced = from the crawler, with a link to the source and no conflict
    sourced = sum(
        1
        for f in facts
        if f.get("origin") == "crawler"
        and isinstance(f.get("citation"), dict)
        and f["citation"].get("url")
        and not f["citation"].get("conflict")
    )
    total = len(facts)
    if not total:
        return _result("unverified", _DEFAULT_SUMMARY)
    checks = [
        _check(
            "Sourced facts",
            "pass" if sourced else "info",
            f"{sourced} of {total} facts link to their source",
        )
    ]
    if sourced == total:
        return _result(
            "verified",
            "Every fact links to its published source",
            checks,
            items_verified=sourced,
            items_total=total,
        )
    if sourced:
        return _result(
            "partial",
            "Some facts link to their source; the rest are AI-suggested or unlinked",
            checks,
            items_verified=sourced,
            items_total=total,
        )
    return _result(
        "unverified",
        "No fact links to a published source",
        checks,
        items_verified=0,
        items_total=total,
    )


def _official_visa(data: dict, ai_type) -> dict | None:
    """Compare with an official entry rule from the crawler (single-country
    trips only), or None when there is nothing to compare."""
    from .crawler_facts import visa_family

    entries = data.get("official_entry")
    if not isinstance(entries, list) or len(entries) != 1:
        return None
    rules = [r for r in entries[0].get("rules") or [] if isinstance(r, dict)]
    ours = visa_family(ai_type)
    for rule in rules:
        src = rule.get("source") if isinstance(rule.get("source"), dict) else {}
        theirs = visa_family(rule.get("visa_type"))
        if not ours or not theirs or src.get("conflict"):
            continue
        name = src.get("name") or src.get("source_id") or "official source"
        url = _str_url(src.get("url"))
        if ours == theirs:
            return _result(
                "verified",
                f"Visa type matches the official source ({name}).",
                [
                    _check(
                        "Official entry rules",
                        "pass",
                        f"Visa type: {rule.get('visa_type')}",
                        url,
                    )
                ],
            )
        return _result(
            "conflict",
            f"AI says {ai_type}; the official source ({name}) says "
            f"{rule.get('visa_type')}. Check the official site.",
            [
                _check(
                    "Official entry rules",
                    "fail",
                    f"AI says {ai_type}; {name} says {rule.get('visa_type')}",
                    url,
                )
            ],
        )
    return None


def _forex(data: dict) -> dict | None:
    rates = [
        r
        for r in data.get("exchange_rates") or []
        if isinstance(r, dict) and isinstance(r.get("rate_source"), dict)
    ]
    if not rates:
        return None
    checks = [
        _check(
            f"{r.get('from_currency')} → {r.get('to_currency')}",
            "pass",
            f"Published by {r['rate_source'].get('name') or r['rate_source'].get('source_id')}"
            + (
                f" (as of {r['rate_source']['as_of']})"
                if r["rate_source"].get("as_of")
                else ""
            ),
            _str_url(r["rate_source"].get("url")),
        )
        for r in rates
    ]
    return _result(
        "partial",
        "Exchange rates are published reference rates; the money tips are AI-generated.",
        checks,
    )


def _visa(data: dict, request: TravelSearchRequest) -> dict:
    req = data.get("requirement") if isinstance(data.get("requirement"), dict) else {}
    ai_type = req.get("visa_type")
    official = _official_visa(data, ai_type)
    if official is not None:
        return official
    table = get_static_visa(request)
    if not table:
        return _result(
            "unverified",
            _DEFAULT_SUMMARY,
            [
                _check(
                    "Reference table",
                    "info",
                    "No reference data for this nationality and destination — confirm on the official site",
                    _str_url(req.get("official_url")),
                )
            ],
        )
    ref = table.get("requirement") or {}
    ref_type = ref.get("visa_type")
    ref_url = _str_url(ref.get("official_url"))
    if not normalise_visa_type(ai_type):
        return _result(
            "unverified",
            _DEFAULT_SUMMARY,
            [
                _check(
                    "Reference table",
                    "info",
                    "No visa type stated to compare — confirm on the official site",
                    ref_url,
                )
            ],
        )
    if normalise_visa_type(ai_type) == normalise_visa_type(ref_type):
        return _result(
            "verified",
            "Visa type matches our reference table.",
            [
                _check(
                    "Matches our reference table",
                    "pass",
                    f"Visa type: {ref_type}",
                    ref_url,
                )
            ],
        )
    return _result(
        "conflict",
        f"AI says {ai_type}; our reference table says {ref_type}. Check the official site.",
        [
            _check(
                "Reference table",
                "fail",
                f"AI says {ai_type}; reference table says {ref_type}",
                ref_url,
            )
        ],
    )


def _compare_numbers(ai: dict, ref: dict) -> tuple[list[tuple[str, str, str]], int]:
    """Return (mismatches [(field, ai, ref)], fields_compared)."""
    mismatches, compared = [], 0
    for field in _EMERGENCY_FIELDS:
        a, r = _digits(ai.get(field)), _digits(ref.get(field))
        if not a or not r:
            continue
        compared += 1
        # "112 or 911" lists alternatives: any digit group matching passes;
        # whole-value digits still cover formatting like "1-1-9" or " 112".
        candidates = {a, *re.findall(r"\d+", str(ai.get(field)))}
        if r not in candidates:
            mismatches.append(
                (field, str(ai.get(field)).strip(), str(ref.get(field)).strip())
            )
    return mismatches, compared


def _emergency(data: dict, request: TravelSearchRequest) -> dict:
    if isinstance(data.get("cities"), list):
        entries = [
            (c.get("city") or "", c) for c in data["cities"] if isinstance(c, dict)
        ]
        multi = True
    else:
        entries = [(request.destination or "", data)]
        multi = False

    checks, conflicts = [], []
    # matched = cities with >=2 numbers compared and all equal (fully checked);
    # thin = cities where only one number could be compared (and it matched)
    matched = thin = 0
    for city, entry in entries:
        ai = (
            entry.get("emergency_numbers")
            if isinstance(entry.get("emergency_numbers"), dict)
            else {}
        )
        ref = get_static_emergency_numbers(city) if city else None
        where = f" in {city}" if multi else ""
        official = entry.get("emergency_numbers_source")
        if isinstance(official, dict):
            # Numbers taken from an official list (crawler): nothing to compare
            matched += 1
            checks.append(
                _check(
                    f"Emergency numbers{where}",
                    "pass",
                    f"From an official source: {official.get('name') or official.get('source_id')}"
                    + (
                        f" (as of {official['as_of']})" if official.get("as_of") else ""
                    ),
                    _str_url(official.get("url")),
                )
            )
            continue
        if not ref:
            checks.append(
                _check(
                    f"Emergency numbers{where}",
                    "info",
                    "No reference data to compare against",
                )
            )
            continue
        mismatches, compared = _compare_numbers(ai, ref)
        if mismatches:
            for field, a, r in mismatches:
                text = f"AI says {field} is {a}{where}; our reference table says {r}"
                conflicts.append(text)
                checks.append(
                    _check(f"{field.capitalize()} number{where}", "fail", text)
                )
        elif compared >= _MIN_EMERGENCY_COMPARED:
            matched += 1
            checks.append(
                _check(f"Emergency numbers{where}", "pass", "Match our reference table")
            )
        elif compared:
            thin += 1
            checks.append(
                _check(
                    f"Emergency numbers{where}",
                    "pass",
                    f"The one number stated matches our reference table "
                    f"(of {len(_EMERGENCY_FIELDS)})",
                )
            )
        else:
            checks.append(
                _check(
                    f"Emergency numbers{where}", "info", "No numbers stated to compare"
                )
            )

    if conflicts:
        return _result(
            "conflict", "; ".join(conflicts) + ". Check official sources.", checks
        )
    if entries and matched == len(entries):
        return _result(
            "verified", "Emergency numbers match our reference table.", checks
        )
    if matched or thin:
        return _result(
            "partial",
            "Some emergency numbers match our reference table; others could not be compared.",
            checks,
        )
    return _result("unverified", _DEFAULT_SUMMARY, checks)


def verify_section(
    name: str,
    data,
    request: TravelSearchRequest,
    *,
    pending: bool = False,
    source: str = "ai",
) -> dict | None:
    """Build the ``verification`` object for one section, or None for errors.

    ``source`` is the SSE event source ('static' for curated Phase-0 tables).
    ``pending`` marks the first hotels/activities/places yield while URL
    enrichment is still running.
    """
    if not isinstance(data, dict) or data.get("error"):
        return None
    if name == "flights":
        return _flights(data)
    if name == "hotels":
        return _hotels(data, pending)
    if name == "activities":
        return _listings(data, pending, with_prices=True)
    if name == "places_to_see":
        return _listings(data, pending, with_prices=False)
    if name == "walking_tours":
        return _walking_tours(data)
    if name == "weather":
        return _weather(data)
    if name == "events":
        return _events(data)
    if name == "facts":
        return _facts(data)
    if name == "visa":
        return _visa(data, request)
    if name == "emergency_card":
        return _emergency(data, request)
    if name == "forex" and source != "static":
        forex = _forex(data)
        if forex is not None:
            return forex
    if name in _REFERENCE_SECTIONS and source == "static":
        return _result(
            "verified",
            _REFERENCE_SUMMARY,
            [_check("Reference data", "pass", "From our curated reference table")],
        )
    return _result("unverified", _DEFAULT_SUMMARY)


def attach_verification(
    name: str,
    data,
    request: TravelSearchRequest,
    *,
    pending: bool = False,
    source: str = "ai",
):
    """Return a NEW dict with ``verification`` attached (or ``data`` unchanged).

    Never mutates ``data``: the same dict may be reused elsewhere (deferred
    agents, enrichment input, static confidence lookup).
    """
    verification = verify_section(name, data, request, pending=pending, source=source)
    if verification is None:
        return data
    return {**data, "verification": verification}
