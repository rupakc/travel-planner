"""Evidence-based source verification labels for search sections.

Pure and deterministic: labels are derived only from evidence the pipeline
already holds (live-fare markers, enrichment link matches, crawl sources,
weather API provenance, curated static tables). No network calls. When there
is no evidence the label says so — never claim verification without it.

Never put a key named ``error`` in the returned object: the search cache
guard treats any truthy ``data.error`` as a failed run.
"""

from __future__ import annotations

import re

from ..agents.static_results import get_static_emergency_numbers, get_static_visa
from ..schemas.request import TravelSearchRequest

_LABELS = {
    "verified": "Verified",
    "partial": "Partly verified",
    "unverified": "AI-generated",
    "conflict": "Check details",
}

_DEFAULT_SUMMARY = "Generated by AI from its training data — verify before booking."
_REFERENCE_SUMMARY = "From our curated reference data (may lag recent changes)"
_PENDING_SUMMARY = "Checking which links can be found online…"

# Static-backed sections whose Phase-0 yield comes from a curated table
_REFERENCE_SECTIONS = {"sim", "tips", "getting_around", "forex"}
_EMERGENCY_FIELDS = ("police", "ambulance", "fire")


def _check(label: str, status: str, detail: str, url: str | None = None) -> dict:
    return {"label": label, "status": status, "detail": detail, "url": url}


def _result(
    level: str,
    summary: str,
    checks: list[dict] | None = None,
    *,
    items_verified: int | None = None,
    items_total: int | None = None,
    pending: bool = False,
) -> dict:
    return {
        "level": level,
        "label": _LABELS[level],
        "summary": summary,
        "checks": checks or [],
        "items_verified": items_verified,
        "items_total": items_total,
        "pending": pending,
    }


def _items(data: dict) -> list[dict]:
    results = data.get("results")
    if not isinstance(results, list):
        return []
    return [r for r in results if isinstance(r, dict)]


def _str_url(value) -> str | None:
    return value if isinstance(value, str) and value else None


def normalise_visa_type(value) -> str:
    """'Visa-free' == 'visa free' == 'VISA_FREE' == ' visa  free '."""
    if not isinstance(value, str):
        return ""
    return " ".join(re.split(r"[\s_\-]+", value.strip().lower())).strip()


def _digits(value) -> str:
    return re.sub(r"\D", "", str(value)) if value is not None else ""


# ── per-section rules ─────────────────────────────────────────────────


def _flights(data: dict) -> dict:
    # `live_fare` is set only by the SerpAPI mapper (and stripped from LLM
    # output); `source` alone is not evidence — the model copies it from its
    # prompt example and URL enrichment rewrites it from the booking link.
    items = _items(data)
    live = sum(1 for f in items if f.get("live_fare") is True)
    total = len(items)
    counts = {"items_verified": live, "items_total": total}
    if total and live == total:
        return _result(
            "verified",
            "Live fares from Google Flights",
            [
                _check(
                    "Live fares", "pass", f"{live} of {total} fares from Google Flights"
                )
            ],
            **counts,
        )
    if live:
        return _result(
            "partial",
            "Some fares are live from Google Flights; the rest are AI estimates — check the airline.",
            [
                _check(
                    "Live fares", "pass", f"{live} of {total} fares from Google Flights"
                ),
                _check(
                    "Estimated fares",
                    "info",
                    f"{total - live} of {total} fares are AI estimates",
                ),
            ],
            **counts,
        )
    return _result(
        "unverified",
        "Estimated fares — prices change; check the airline",
        [_check("Estimated fares", "info", "Fares are AI estimates, not live prices")],
        **counts,
    )


def _hotels(data: dict, pending: bool) -> dict:
    # Only items enrichment actually searched carry a bool; absent = not searched
    searched = [h for h in _items(data) if isinstance(h.get("link_verified"), bool)]
    found = sum(1 for h in searched if h["link_verified"] is True)
    total = len(searched)
    checks = (
        [
            _check(
                "Hotel listings",
                "pass" if found else "info",
                f"Found online by name: {found} of {total}",
            )
        ]
        if total
        else []
    )
    counts = {"items_verified": found, "items_total": total, "pending": pending}
    if pending:
        return _result("unverified", _PENDING_SUMMARY, [], **counts)
    if total and found == total:
        return _result(
            "verified",
            "Every checked hotel was found online by name.",
            checks,
            **counts,
        )
    if found:
        return _result(
            "partial",
            "Some hotels were found online by name; verify the rest before booking.",
            checks,
            **counts,
        )
    if not total:
        return _result(
            "unverified",
            "No hotels were checked online — verify before booking.",
            checks,
            **counts,
        )
    return _result("unverified", _DEFAULT_SUMMARY, checks, **counts)


def _listings(data: dict, pending: bool, *, with_prices: bool) -> dict:
    items = _items(data)
    found = sum(1 for a in items if a.get("link_verified") is True)
    total = len(items)
    counts = {"items_verified": found, "items_total": total, "pending": pending}
    if pending:
        return _result("unverified", _PENDING_SUMMARY, [], **counts)
    if found:
        checks = [
            _check(
                "Specific listings",
                "pass",
                f"{found} of {total} link to a specific listing found online",
            )
        ]
        summary = "Some links point to listings found online; the rest are searches."
        level = "partial"
    else:
        checks = [
            _check(
                "Specific listings", "info", "Links are searches, not specific listings"
            )
        ]
        summary = _DEFAULT_SUMMARY
        level = "unverified"
    if with_prices:
        checks.append(
            _check("Prices and ratings", "info", "Prices and ratings are AI estimates")
        )
    return _result(level, summary, checks, **counts)


def _walking_tours(data: dict) -> dict:
    checks = []
    ok = 0
    for s in data.get("sources") or []:
        if not isinstance(s, dict):
            continue
        provider = s.get("provider") or s.get("provider_key") or "Provider"
        city = f" ({s['city']})" if s.get("city") else ""
        if s.get("status") == "ok":
            ok += 1
            checks.append(
                _check(
                    f"{provider}{city}",
                    "pass",
                    f"{s.get('count', 0)} tours crawled from the provider's page",
                    _str_url(s.get("url")),
                )
            )
        else:
            checks.append(
                _check(
                    f"{provider}{city}",
                    "info",
                    "Provider page could not be read this time",
                    _str_url(s.get("url")),
                )
            )
    if ok and _items(data):
        return _result(
            "verified", "Listings crawled from the providers' own pages", checks
        )
    return _result(
        "unverified", "No provider listings could be confirmed this time.", checks
    )


def _weather(data: dict) -> dict:
    source = data.get("source") if isinstance(data.get("source"), str) else ""
    if source == "open-meteo":
        return _result(
            "verified",
            "Open-Meteo forecast/climate data",
            [
                _check(
                    "Open-Meteo",
                    "pass",
                    "Forecast/climate data from Open-Meteo",
                    "https://open-meteo.com",
                )
            ],
        )
    if "open-meteo" in source and "llm-estimate" in source:
        return _result(
            "partial",
            "Partly Open-Meteo data; some cities are AI climate estimates.",
            [
                _check(
                    "Open-Meteo",
                    "pass",
                    "Some cities from Open-Meteo",
                    "https://open-meteo.com",
                ),
                _check("AI estimate", "info", "Some cities are AI climate estimates"),
            ],
        )
    return _result(
        "unverified",
        "AI climate estimate — check a forecast closer to your trip.",
        [_check("AI estimate", "info", "No live forecast data was available")],
    )


def _events(data: dict) -> dict:
    items = _items(data)
    checks = []
    if items:
        confirmed = sum(
            1 for e in items if e.get("date_certainty") == "confirmed_annual"
        )
        checks.append(
            _check(
                "Event dates",
                "info",
                f"{confirmed} of {len(items)} dates confirmed annual",
            )
        )
    return _result("unverified", _DEFAULT_SUMMARY, checks)


def _visa(data: dict, request: TravelSearchRequest) -> dict:
    req = data.get("requirement") if isinstance(data.get("requirement"), dict) else {}
    ai_type = req.get("visa_type")
    table = get_static_visa(request)
    if not table:
        return _result(
            "unverified",
            _DEFAULT_SUMMARY,
            [
                _check(
                    "Reference table",
                    "info",
                    "No reference data for this nationality and destination — confirm on the official site",
                    _str_url(req.get("official_url")),
                )
            ],
        )
    ref = table.get("requirement") or {}
    ref_type = ref.get("visa_type")
    ref_url = _str_url(ref.get("official_url"))
    if not normalise_visa_type(ai_type):
        return _result(
            "unverified",
            _DEFAULT_SUMMARY,
            [
                _check(
                    "Reference table",
                    "info",
                    "No visa type stated to compare — confirm on the official site",
                    ref_url,
                )
            ],
        )
    if normalise_visa_type(ai_type) == normalise_visa_type(ref_type):
        return _result(
            "verified",
            "Visa type matches our reference table.",
            [
                _check(
                    "Matches our reference table",
                    "pass",
                    f"Visa type: {ref_type}",
                    ref_url,
                )
            ],
        )
    return _result(
        "conflict",
        f"AI says {ai_type}; our reference table says {ref_type}. Check the official site.",
        [
            _check(
                "Reference table",
                "fail",
                f"AI says {ai_type}; reference table says {ref_type}",
                ref_url,
            )
        ],
    )


def _compare_numbers(ai: dict, ref: dict) -> tuple[list[tuple[str, str, str]], int]:
    """Return (mismatches [(field, ai, ref)], fields_compared)."""
    mismatches, compared = [], 0
    for field in _EMERGENCY_FIELDS:
        a, r = _digits(ai.get(field)), _digits(ref.get(field))
        if not a or not r:
            continue
        compared += 1
        # "112 or 911" lists alternatives: any digit group matching passes;
        # whole-value digits still cover formatting like "1-1-9" or " 112".
        candidates = {a, *re.findall(r"\d+", str(ai.get(field)))}
        if r not in candidates:
            mismatches.append(
                (field, str(ai.get(field)).strip(), str(ref.get(field)).strip())
            )
    return mismatches, compared


def _emergency(data: dict, request: TravelSearchRequest) -> dict:
    if isinstance(data.get("cities"), list):
        entries = [
            (c.get("city") or "", c) for c in data["cities"] if isinstance(c, dict)
        ]
        multi = True
    else:
        entries = [(request.destination or "", data)]
        multi = False

    checks, conflicts = [], []
    matched = 0
    for city, entry in entries:
        ai = (
            entry.get("emergency_numbers")
            if isinstance(entry.get("emergency_numbers"), dict)
            else {}
        )
        ref = get_static_emergency_numbers(city) if city else None
        where = f" in {city}" if multi else ""
        if not ref:
            checks.append(
                _check(
                    f"Emergency numbers{where}",
                    "info",
                    "No reference data to compare against",
                )
            )
            continue
        mismatches, compared = _compare_numbers(ai, ref)
        if mismatches:
            for field, a, r in mismatches:
                text = f"AI says {field} is {a}{where}; our reference table says {r}"
                conflicts.append(text)
                checks.append(
                    _check(f"{field.capitalize()} number{where}", "fail", text)
                )
        elif compared:
            matched += 1
            checks.append(
                _check(f"Emergency numbers{where}", "pass", "Match our reference table")
            )
        else:
            checks.append(
                _check(
                    f"Emergency numbers{where}", "info", "No numbers stated to compare"
                )
            )

    if conflicts:
        return _result(
            "conflict", "; ".join(conflicts) + ". Check official sources.", checks
        )
    if entries and matched == len(entries):
        return _result(
            "verified", "Emergency numbers match our reference table.", checks
        )
    if matched:
        return _result(
            "partial",
            "Some emergency numbers match our reference table; others have no reference data.",
            checks,
        )
    return _result("unverified", _DEFAULT_SUMMARY, checks)


def verify_section(
    name: str,
    data,
    request: TravelSearchRequest,
    *,
    pending: bool = False,
    source: str = "ai",
) -> dict | None:
    """Build the ``verification`` object for one section, or None for errors.

    ``source`` is the SSE event source ('static' for curated Phase-0 tables).
    ``pending`` marks the first hotels/activities/places yield while URL
    enrichment is still running.
    """
    if not isinstance(data, dict) or data.get("error"):
        return None
    if name == "flights":
        return _flights(data)
    if name == "hotels":
        return _hotels(data, pending)
    if name == "activities":
        return _listings(data, pending, with_prices=True)
    if name == "places_to_see":
        return _listings(data, pending, with_prices=False)
    if name == "walking_tours":
        return _walking_tours(data)
    if name == "weather":
        return _weather(data)
    if name == "events":
        return _events(data)
    if name == "visa":
        return _visa(data, request)
    if name == "emergency_card":
        return _emergency(data, request)
    if name in _REFERENCE_SECTIONS and source == "static":
        return _result(
            "verified",
            _REFERENCE_SUMMARY,
            [_check("Reference data", "pass", "From our curated reference table")],
        )
    return _result("unverified", _DEFAULT_SUMMARY)
