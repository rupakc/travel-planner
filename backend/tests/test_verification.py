# ── stream wiring (fake agents, no network) ───────────────────────────


class _FakeAgent:
    def __init__(self, result, enriched=None, enrich_raises=False):
        self._result = result
        self._enriched = enriched
        self._raises = enrich_raises
        self.calls: list[dict] = []

    async def run(self, request, **kw):
        self.calls.append(kw)
        return copy.deepcopy(self._result)

    async def enrich(self, data):
        if self._raises:
            raise RuntimeError("ddg down")
        return self._enriched if self._enriched is not None else data


async def test_stream_run_attaches_verification_everywhere():
    from app.agents.orchestrator import TravelOrchestrator

    orch = TravelOrchestrator.__new__(TravelOrchestrator)
    hotels_enriched = {"results": [{"name": "A", "link_verified": True}]}
    orch.flights = _FakeAgent({"results": [{"source": "estimate", "price_usd": 500}]})
    orch.hotels = _FakeAgent({"results": [{"name": "A"}]}, enriched=hotels_enriched)
    orch.activities = _FakeAgent({"results": [{"name": "X"}]}, enrich_raises=True)
    orch.places = _FakeAgent({"results": [{"name": "P"}]})
    orch.visa = _FakeAgent({"requirement": {"visa_type": "e-visa"}})
    orch.emergency_card = _FakeAgent({"error": "boom"})
    for attr in [
        "weather",
        "walking_tours",
        "events",
        "sim",
        "tips",
        "getting_around",
        "forex",
        "pricing_advisor",
    ]:
        setattr(orch, attr, _FakeAgent({"ok": True}))
    orch.itinerary = _FakeAgent({"days": [{"day": 1}]})
    orch.packing_list = _FakeAgent({"categories": []})
    orch.stress_test = _FakeAgent({"overall": "ok"})

    events = []
    async for chunk in orch.stream_run(REQ):
        if chunk.startswith("data: "):
            events.append(json.loads(chunk[6:]))

    sections = [
        e for e in events if e.get("type") not in {"agent_status", "done", "confidence"}
    ]
    for e in sections:
        data = e["data"]
        if data.get("error"):
            assert "verification" not in data
        else:
            assert "verification" in data, e["type"]

    def of(t):
        return [e["data"]["verification"] for e in sections if e["type"] == t]

    assert [v["pending"] for v in of("hotels")] == [True, False]
    assert of("hotels")[-1]["level"] == "verified"
    # enrichment failed → pending resolved on the unenriched data
    assert [v["pending"] for v in of("activities")] == [True, False]
    assert of("places_to_see")[0]["pending"] is True
    assert of("places_to_see")[-1]["pending"] is False
    visa = of("visa")
    assert visa[0]["level"] == "verified"  # Phase-0 static
    assert visa[-1]["level"] == "conflict"  # AI disagrees
    assert (
        of("sim")[0]["level"] == "verified" and of("sim")[-1]["level"] == "unverified"
    )
    for t in ["itinerary", "packing_list", "stress_test", "pricing_advisor", "flights"]:
        assert of(t), t
    # emergency AI errored → only the static yield, verified
    assert [v["level"] for v in of("emergency_card")] == ["verified"]

    # downstream agents never see the UI-only verification object
    for agent in (orch.itinerary, orch.stress_test, orch.packing_list):
        assert agent.calls, agent
        assert not _contains_key(agent.calls, "verification")


def _contains_key(obj, key) -> bool:
    if isinstance(obj, dict):
        return key in obj or any(_contains_key(v, key) for v in obj.values())
    if isinstance(obj, list):
        return any(_contains_key(v, key) for v in obj)
    return False


