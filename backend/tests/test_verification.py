def _req(**kw) -> TravelSearchRequest:
    base = {
        "origin": "NYC",
        "destination": "Tokyo",
        "departure_date": date(2026, 11, 1),
        "return_date": date(2026, 11, 8),
        "interests": ["food"],
        "nationality": "American",
        "residence_permits": [],
        "existing_visas": [],
        "budget_usd": 3000,
        "num_travelers": 1,
        "destinations": [],
    }
    base.update(kw)
    return TravelSearchRequest.model_construct(**base)


REQ = _req()  # American → Tokyo: in the visa and emergency tables
REQ_UNKNOWN = _req(nationality="Brazilian", destination="Atlantis")


def _shape_ok(v: dict) -> None:
    assert set(v) == {
        "level",
        "label",
        "summary",
        "checks",
        "items_verified",
        "items_total",
        "pending",
    }
    assert (
        v["label"]
        == {
            "verified": "Verified",
            "partial": "Partly verified",
            "unverified": "AI-generated",
            "conflict": "Check details",
        }[v["level"]]
    )
    for c in v["checks"]:
        assert set(c) == {"label", "status", "detail", "url"}
        assert c["status"] in {"pass", "fail", "info"}
    # never a key named `error` anywhere (cache guard)
    assert '"error"' not in json.dumps(v)


